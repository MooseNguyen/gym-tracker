-- Gym Tracker initial schema.
-- Security model: every row belongs to a user (directly or through its parent),
-- and Row Level Security is the only thing that enforces it.

create type exercise_kind as enum ('weight_reps', 'bodyweight_reps', 'duration');
create type set_type as enum ('warmup', 'normal', 'drop', 'failure');

-- Exercises: user_id null = built-in exercise visible to everyone.
create table exercises (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users (id) on delete cascade default auth.uid(),
  name text not null check (length(trim(name)) > 0),
  muscle_group text not null,
  equipment text not null,
  kind exercise_kind not null default 'weight_reps',
  created_at timestamptz not null default now()
);
create index exercises_user_id_idx on exercises (user_id);

create table routines (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  name text not null check (length(trim(name)) > 0),
  notes text,
  created_at timestamptz not null default now()
);
create index routines_user_id_idx on routines (user_id);

create table routine_exercises (
  id uuid primary key default gen_random_uuid(),
  routine_id uuid not null references routines (id) on delete cascade,
  exercise_id uuid not null references exercises (id) on delete restrict,
  position int not null,
  target_sets int not null default 3 check (target_sets between 1 and 20),
  rest_seconds int not null default 90 check (rest_seconds between 0 and 900)
);
create index routine_exercises_routine_id_idx on routine_exercises (routine_id);
create index routine_exercises_exercise_id_idx on routine_exercises (exercise_id);

-- workouts.id is generated by the client so that saving is idempotent.
create table workouts (
  id uuid primary key,
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  routine_id uuid references routines (id) on delete set null,
  name text not null,
  started_at timestamptz not null,
  ended_at timestamptz not null,
  notes text,
  check (ended_at >= started_at)
);
create index workouts_user_started_idx on workouts (user_id, started_at desc);

create table workout_exercises (
  id uuid primary key default gen_random_uuid(),
  workout_id uuid not null references workouts (id) on delete cascade,
  -- restrict: deleting an exercise must not silently delete workout history
  exercise_id uuid not null references exercises (id) on delete restrict,
  position int not null,
  notes text
);
create index workout_exercises_workout_id_idx on workout_exercises (workout_id);
create index workout_exercises_exercise_id_idx on workout_exercises (exercise_id);

create table sets (
  id uuid primary key default gen_random_uuid(),
  workout_exercise_id uuid not null references workout_exercises (id) on delete cascade,
  position int not null,
  set_type set_type not null default 'normal',
  weight_kg numeric(6, 2) check (weight_kg >= 0),
  reps int check (reps >= 0),
  duration_s int check (duration_s >= 0),
  rpe numeric(3, 1) check (rpe between 1 and 10)
);
create index sets_workout_exercise_id_idx on sets (workout_exercise_id);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- (select auth.uid()) instead of auth.uid() lets Postgres evaluate it once per
-- query instead of once per row.
-- ---------------------------------------------------------------------------
alter table exercises enable row level security;
alter table routines enable row level security;
alter table routine_exercises enable row level security;
alter table workouts enable row level security;
alter table workout_exercises enable row level security;
alter table sets enable row level security;

create policy "read built-in and own exercises" on exercises
  for select to authenticated using (user_id is null or user_id = (select auth.uid()));
create policy "insert own exercises" on exercises
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "update own exercises" on exercises
  for update to authenticated using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
create policy "delete own exercises" on exercises
  for delete to authenticated using (user_id = (select auth.uid()));

create policy "own routines" on routines
  for all to authenticated using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- True if the caller may use this exercise: built-in or their own.
-- security invoker on purpose: the query goes through the exercises SELECT
-- policy, so this stays correct if that policy changes.
create or replace function can_use_exercise(p_exercise_id uuid)
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select exists (select 1 from exercises where id = p_exercise_id);
$$;

-- with check also validates exercise_id: owning the parent row is not enough,
-- otherwise a user could attach someone else's custom exercise by its UUID.
create policy "own routine exercises" on routine_exercises
  for all to authenticated
  using (exists (select 1 from routines r where r.id = routine_id and r.user_id = (select auth.uid())))
  with check (
    exists (select 1 from routines r where r.id = routine_id and r.user_id = (select auth.uid()))
    and can_use_exercise(exercise_id)
  );

create policy "own workouts" on workouts
  for all to authenticated using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy "own workout exercises" on workout_exercises
  for all to authenticated
  using (exists (select 1 from workouts w where w.id = workout_id and w.user_id = (select auth.uid())))
  with check (
    exists (select 1 from workouts w where w.id = workout_id and w.user_id = (select auth.uid()))
    and can_use_exercise(exercise_id)
  );

create policy "own sets" on sets
  for all to authenticated
  using (exists (
    select 1 from workout_exercises we join workouts w on w.id = we.workout_id
    where we.id = workout_exercise_id and w.user_id = (select auth.uid())))
  with check (exists (
    select 1 from workout_exercises we join workouts w on w.id = we.workout_id
    where we.id = workout_exercise_id and w.user_id = (select auth.uid())));

-- ---------------------------------------------------------------------------
-- RPCs. security invoker = they run as the caller, so RLS still applies.
-- ---------------------------------------------------------------------------

-- Saves a whole workout in one transaction. Used both for finishing a new
-- workout and for editing an old one: children are replaced wholesale.
-- Calling it twice with the same payload gives the same result (idempotent).
create or replace function save_workout(p jsonb)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  w_id uuid := (p ->> 'id')::uuid;
  ex jsonb;
  s jsonb;
  we_id uuid;
  ex_pos int := 0;
  s_pos int;
begin
  -- If the id belongs to another user, RLS hides that row, the insert hits the
  -- primary key and the update branch fails its policy: it raises instead of
  -- overwriting someone else's data.
  insert into workouts (id, routine_id, name, started_at, ended_at, notes)
  values (
    w_id,
    nullif(p ->> 'routine_id', '')::uuid,
    p ->> 'name',
    (p ->> 'started_at')::timestamptz,
    (p ->> 'ended_at')::timestamptz,
    p ->> 'notes'
  )
  on conflict (id) do update set
    routine_id = excluded.routine_id,
    name = excluded.name,
    started_at = excluded.started_at,
    ended_at = excluded.ended_at,
    notes = excluded.notes;

  delete from workout_exercises where workout_id = w_id;

  for ex in select * from jsonb_array_elements(coalesce(p -> 'exercises', '[]'::jsonb)) loop
    insert into workout_exercises (workout_id, exercise_id, position, notes)
    values (w_id, (ex ->> 'exercise_id')::uuid, ex_pos, ex ->> 'notes')
    returning id into we_id;

    s_pos := 0;
    for s in select * from jsonb_array_elements(coalesce(ex -> 'sets', '[]'::jsonb)) loop
      insert into sets (workout_exercise_id, position, set_type, weight_kg, reps, duration_s, rpe)
      values (
        we_id,
        s_pos,
        coalesce(s ->> 'set_type', 'normal')::set_type,
        (s ->> 'weight_kg')::numeric,
        (s ->> 'reps')::int,
        (s ->> 'duration_s')::int,
        (s ->> 'rpe')::numeric
      );
      s_pos := s_pos + 1;
    end loop;

    ex_pos := ex_pos + 1;
  end loop;

  return w_id;
end;
$$;

-- Saves a routine and replaces its exercise list in one transaction.
create or replace function save_routine(p jsonb)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  r_id uuid := nullif(p ->> 'id', '')::uuid;
  ex jsonb;
  pos int := 0;
begin
  if r_id is null then
    insert into routines (name, notes) values (p ->> 'name', p ->> 'notes')
    returning id into r_id;
  else
    update routines set name = p ->> 'name', notes = p ->> 'notes' where id = r_id;
    if not found then
      raise exception 'Routine % not found', r_id using errcode = 'P0002';
    end if;
    delete from routine_exercises where routine_id = r_id;
  end if;

  for ex in select * from jsonb_array_elements(coalesce(p -> 'exercises', '[]'::jsonb)) loop
    insert into routine_exercises (routine_id, exercise_id, position, target_sets, rest_seconds)
    values (
      r_id,
      (ex ->> 'exercise_id')::uuid,
      pos,
      coalesce((ex ->> 'target_sets')::int, 3),
      coalesce((ex ->> 'rest_seconds')::int, 90)
    );
    pos := pos + 1;
  end loop;

  return r_id;
end;
$$;

-- Sets from the most recent workout that contains each given exercise.
-- Powers the "previous" column while logging.
create or replace function previous_sets(p_exercise_ids uuid[], p_exclude_workout uuid default null)
returns table (
  exercise_id uuid,
  "position" int,
  set_type set_type,
  weight_kg numeric,
  reps int,
  duration_s int,
  rpe numeric
)
language sql
stable
security invoker
set search_path = public
as $$
  with latest as (
    select distinct on (we.exercise_id) we.id, we.exercise_id
    from workout_exercises we
    join workouts w on w.id = we.workout_id
    where we.exercise_id = any (p_exercise_ids)
      and (p_exclude_workout is null or w.id <> p_exclude_workout)
    order by we.exercise_id, w.started_at desc
  )
  select l.exercise_id, s.position, s.set_type, s.weight_kg, s.reps, s.duration_s, s.rpe
  from latest l
  join sets s on s.workout_exercise_id = l.id
  order by l.exercise_id, s.position;
$$;
