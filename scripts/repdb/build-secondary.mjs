// Fills exercises.secondary_muscles for the RepDB built-ins from RepDB's own
// secondary_muscles, as the app's muscle values. Writes a migration.
//
//   node scripts/repdb/build-secondary.mjs
import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { sqlString } from '../sql.mjs'
import { loadRepdb, root, secondaryFor } from './repdb.mjs'

const MIGRATION = 'supabase/migrations/20261114000000_secondary_muscles.sql'

const committed = (() => {
  try {
    execFileSync('git', ['ls-files', '--error-unmatch', MIGRATION], { cwd: root, stdio: 'ignore' })
    return true
  } catch {
    return false
  }
})()
if (committed && !process.argv.includes('--force')) {
  throw new Error(`${MIGRATION} is committed (and maybe applied): write a new migration instead`)
}

const library = JSON.parse(await readFile(path.join(root, 'scripts/repdb/library.json'), 'utf8'))
const byId = new Map((await loadRepdb()).map((e) => [e.id, e]))
const rows = library
  .map(({ id }) => ({ id, muscles: secondaryFor(byId.get(id)) }))
  .filter((r) => r.muscles.length > 0)

const values = rows
  .map(
    (r) =>
      `  (${sqlString(`repdb-${r.id}.webp`)}, array[${r.muscles.map(sqlString).join(', ')}]::text[])`,
  )
  .join(',\n')
const update = `update exercises e
set secondary_muscles = v.muscles
from (values
${values}
) as v (image_path, muscles)
where e.user_id is null and e.image_path = v.image_path;
`

await writeFile(
  path.join(root, MIGRATION),
  `-- Muscles an exercise also works, besides its primary muscle_group (the app's
-- muscle values). Weekly stats count them too. Built-ins get RepDB's
-- secondary muscles, matched by their RepDB photo (a stable id).
-- GENERATED by scripts/repdb/build-secondary.mjs, do not edit by hand.

alter table exercises add column secondary_muscles text[] not null default '{}';

${update}`,
)

console.log(`secondary muscles for ${rows.length} of ${library.length} RepDB built-ins`)
