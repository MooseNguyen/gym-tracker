// Generates the migration that stores step-by-step instructions for the
// built-in exercises, from free-exercise-db (public domain), using the same
// hand-checked name → dataset id mapping as the photos.
//
//   node scripts/build-instructions-migration.mjs
//
// Writes supabase/migrations/20261108000000_exercise_instructions.sql.
// The output is committed; re-run only if the mapping changes, and then as a
// NEW migration if the old one already ran on the database.
import { writeFile, readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { sqlString, sqlTextArray } from './sql.mjs'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const DATASET =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json'
const out = path.join(root, 'supabase', 'migrations', '20261108000000_exercise_instructions.sql')

const mapping = JSON.parse(
  await readFile(path.join(root, 'scripts', 'exercise-images.json'), 'utf8'),
)
delete mapping._source

const res = await fetch(DATASET)
if (!res.ok) throw new Error(`Dataset download failed: HTTP ${res.status}`)
const dataset = await res.json()
const byId = new Map(dataset.map((e) => [e.id, e]))

const updates = []
const missing = []
for (const [name, id] of Object.entries(mapping)) {
  // Trim and drop empty steps: some entries have stray whitespace.
  const steps = (byId.get(id)?.instructions ?? []).map((s) => s.trim()).filter(Boolean)
  if (steps.length === 0) {
    missing.push(name)
    continue
  }
  updates.push(
    `update exercises set instructions = ${sqlTextArray(steps)}\n` +
      `where user_id is null and name = ${sqlString(name)};`,
  )
}

const sql = `-- Step-by-step instructions for the built-in exercises.
-- GENERATED by scripts/build-instructions-migration.mjs, do not edit by hand.
-- Source: free-exercise-db (https://github.com/yuhonas/free-exercise-db), public domain.

-- null = no instructions (custom exercises, for now).
alter table exercises add column instructions text[];

${updates.join('\n\n')}
`

await writeFile(out, sql)
console.log(`Wrote ${path.relative(root, out)}: ${updates.length} exercises.`)
if (missing.length) {
  console.error(`No instructions for: ${missing.join(', ')}`)
  process.exitCode = 1
}
