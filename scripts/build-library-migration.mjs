// Generates the migration that adds the built-in exercises listed in
// scripts/exercise-library.json, with their photo path and how-to steps from
// free-exercise-db (public domain).
//
//   node scripts/build-library-migration.mjs
//
// Writes supabase/migrations/20261110000000_exercise_library.sql. The output is
// committed; to add more exercises later, append to the JSON and write a NEW
// migration (rename `out`) — the insert skips names that already exist, so the
// same list can be applied again safely.
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { imageFileName, libraryProblems, loadLibrary, loadSeedMapping, root } from './library.mjs'
import { sqlString, sqlTextArray } from './sql.mjs'

const DATASET =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json'
const out = path.join(root, 'supabase', 'migrations', '20261110000000_exercise_library.sql')

const library = await loadLibrary()
const problems = libraryProblems(await loadSeedMapping(), library)
if (problems.length) throw new Error(`Library has conflicts:\n${problems.join('\n')}`)

const res = await fetch(DATASET)
if (!res.ok) throw new Error(`Dataset download failed: HTTP ${res.status}`)
const byId = new Map((await res.json()).map((e) => [e.id, e]))

const missing = library.filter((e) => !byId.has(e.datasetId)).map((e) => e.datasetId)
if (missing.length) throw new Error(`Unknown dataset ids: ${missing.join(', ')}`)

const rows = library.map((e) => {
  // Trim and drop empty steps: some entries have stray whitespace.
  const steps = byId
    .get(e.datasetId)
    .instructions.map((s) => s.trim())
    .filter(Boolean)
  return `  (${[
    sqlString(e.name),
    sqlString(e.muscle_group),
    sqlString(e.equipment),
    sqlString(e.kind),
    sqlString(imageFileName(e.name)),
    steps.length ? sqlTextArray(steps) : 'null::text[]',
  ].join(', ')})`
})

const sql = `-- More built-in exercises (${library.length}), with photo and how-to steps.
-- GENERATED by scripts/build-library-migration.mjs from scripts/exercise-library.json,
-- do not edit by hand.
-- Source: free-exercise-db (https://github.com/yuhonas/free-exercise-db), public domain.

-- Built-ins have user_id null (visible to everyone). Names that already exist
-- as built-ins are skipped, so re-running the same list adds nothing.
insert into exercises (user_id, name, muscle_group, equipment, kind, image_path, instructions)
select null::uuid, v.name, v.muscle_group, v.equipment, v.kind::exercise_kind, v.image_path, v.instructions
from (values
${rows.join(',\n')}
) as v (name, muscle_group, equipment, kind, image_path, instructions)
where not exists (
  select 1 from exercises e where e.user_id is null and e.name = v.name
);
`

await writeFile(out, sql)
console.log(`Wrote ${path.relative(root, out)}: ${library.length} exercises.`)
